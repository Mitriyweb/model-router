/**
 * Generates `.env.example` from the provider registry so documentation cannot
 * drift away from the defaults actually used at runtime.
 *
 * Usage:
 *   bun run env:generate      # write .env.example
 *   bun run env:check         # fail if .env.example is out of date
 */
import fs from "node:fs";
import path from "node:path";
import {
  PROVIDERS,
  VALID_TIERS,
  type CredentialField,
  type ProviderDefinition,
} from "../src/providers/definitions";

const root = path.resolve(import.meta.dir, "..");
const target = path.join(root, ".env.example");

const credentialValue: Record<CredentialField, string> = {
  apiKey: "...",
  apiToken: "...",
  accountId: "...",
};

function baseUrlLines(definition: ProviderDefinition): string[] {
  const name = `${definition.envPrefix}_BASE_URL`;
  if (typeof definition.baseUrlDefault !== "function") {
    return [`${name}=${definition.baseUrlDefault}`];
  }
  return [
    `# ${name} is derived from the credentials below; uncomment to override.`,
    `# ${name}=${definition.baseUrlDefault(() => "…")}`,
  ];
}

function providerSection(definition: ProviderDefinition): string {
  const prefix = definition.envPrefix;
  const credentials = (definition.credentials ?? ["apiKey"]) as readonly CredentialField[];
  const lines = [`# ${definition.label} — ${definition.description}`];

  for (const field of credentials) {
    lines.push(`${prefix}_${fieldName(field)}=${credentialValue[field]}`);
  }
  if (definition.envExtras?.includes("provider")) {
    lines.push(`${prefix}_PROVIDER=`);
  }
  if (definition.requiresModel) {
    lines.push(`# A model is required for ${definition.label} to be usable.`);
  }

  lines.push(
    ...baseUrlLines(definition),
    `${prefix}_MODEL=${definition.modelDefault}`,
    `${prefix}_RPM=${definition.limits.rpm}`,
    `${prefix}_TPM=${definition.limits.tpm}`,
    `${prefix}_RPD=${definition.limits.rpd}`,
  );

  return lines.join("\n");
}

function fieldName(field: CredentialField): string {
  return field === "apiKey" ? "API_KEY" : field === "apiToken" ? "API_TOKEN" : "ACCOUNT_ID";
}

const generated = [
  "# Generated by scripts/generate-env-example.ts — do not edit by hand.",
  "# Run `bun run env:generate` after changing src/providers/definitions.ts.",
  "",
  "# Server",
  "ROUTER_HOST=127.0.0.1",
  "PORT=8787",
  "# Log verbosity: debug | info | warn | error | silent (default: info).",
  "LOG_LEVEL=info",
  "# Optional Bearer token required by /reset, /reset-state and /v1/reset.",
  "ROUTER_AUTH_TOKEN=",
  "# Disable the exact-repeat cache (true/false).",
  "ROUTER_DISABLE_CACHE=false",
  "ROUTER_CACHE_TTL_MS=600000",
  "ROUTER_CACHE_MAX_ENTRIES=500",
  "ROUTER_MAX_BODY_BYTES=1048576",
  "# Empty disables CORS; use * or an http(s) origin.",
  "ROUTER_CORS_ORIGIN=",
  "ROUTER_MAX_CONTEXT_TOKENS=128000",
  "RATE_LIMIT_STATE_FILE=.router-state.json",
  "",
  `# Tier order preference: ${VALID_TIERS.join(",")}`,
  `FALLBACK_ORDER=${VALID_TIERS.join(",")}`,
  "# Fail startup instead of ignoring unknown tiers in FALLBACK_ORDER.",
  "ROUTER_STRICT_FALLBACK_ORDER=false",
  "",
  ...Object.values(PROVIDERS).flatMap((definition) => [
    providerSection(definition as ProviderDefinition),
    "",
  ]),
].join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== generated) {
    console.error(
      ".env.example is out of date. Run `bun run env:generate` and commit the result.",
    );
    process.exit(1);
  }
  console.log(".env.example matches the provider registry.");
} else {
  fs.writeFileSync(target, generated);
  console.log(`Wrote ${target}`);
}
